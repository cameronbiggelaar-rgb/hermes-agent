"""RESTORE-002 Fault B: the stop drain must fit inside the *live* systemd TimeoutStopSec.

Observed failure (2026-11-03 cutover): the shipped unit had ``TimeoutStopSec=210`` while
``restart_drain_timeout=180``.  The drain consumed 180.1 s of the envelope, leaving ~30 s for
interrupt + settle (budget 45 s) + finalize + quiesce + SessionDB close; the only reason the box was
not SIGKILLed was a temporary ``95-timeout-stop.conf`` raising the limit to 300 s.  Sizing the unit
at drain+30 could never have fixed this: the headroom was smaller than the teardown it had to hold.

These tests pin the two halves of the durable fix:

* ``resolve_systemd_timeout_stop_sec`` leaves >= ``SYSTEMD_POST_DRAIN_RESERVE_S`` after the drain —
  so a unit generated by *this* code never needs the cap;
* ``effective_stop_drain_timeout`` / ``effective_stop_watchdog_delay`` clamp a stop to the *live*
  unit budget — so a stale or hand-edited unit degrades the drain instead of losing the teardown.
"""
from types import SimpleNamespace

import pytest

from gateway.restart import (
    LAUNCHD_WATCHDOG_DUMP_MARGIN_S,
    SYSTEMD_POST_DRAIN_RESERVE_S,
    SYSTEMD_WATCHDOG_DUMP_MARGIN_S,
    effective_stop_drain_timeout,
    effective_stop_watchdog_delay,
    resolve_systemd_capped_drain,
    resolve_systemd_timeout_stop_sec,
)
from gateway.run_shutdown import resolve_shutdown_watchdog_delay


def _runner(**kwargs):
    """Bare stop-path double (the shutdown tests never build a real GatewayRunner)."""
    defaults = {
        "_restart_drain_timeout": 180.0,
        "_stop_requested_by_signal": False,
        "_launchd_exit_timeout_s": None,
        "_systemd_timeout_stop_sec": None,
    }
    defaults.update(kwargs)
    return SimpleNamespace(**defaults)


class TestCappedDrain:
    def test_stale_210s_unit_leaves_the_teardown_reserve(self):
        # The drain gives up exactly the reserve so interrupt+settle+close still fit.
        assert resolve_systemd_capped_drain(180.0, 210.0) == 210.0 - SYSTEMD_POST_DRAIN_RESERVE_S

    def test_generous_unit_keeps_the_configured_drain(self):
        assert resolve_systemd_capped_drain(180.0, 300.0) == 180.0
        assert resolve_systemd_capped_drain(180.0, 180.0 + SYSTEMD_POST_DRAIN_RESERVE_S) == 180.0

    def test_short_unit_collapses_the_drain_instead_of_overspending(self):
        # Nothing graceful fits; interrupt immediately and let the 20 s buy the teardown.
        assert resolve_systemd_capped_drain(180.0, 50.0) == 0.0

    @pytest.mark.parametrize("budget", [None, 0, 0.0, -5, "unknown", float("nan"), float("inf")])
    def test_pure_cap_ignores_an_unknown_budget_but_the_caller_must_fail_closed(self, budget):
        # resolve_systemd_capped_drain stays a pure "cap by a known budget"; the fail-closed
        # decision for an unknown budget lives in effective_stop_drain_timeout (see
        # test_stop_budget_probe_failclosed.py, which pins drain 0 on a managed host).
        assert resolve_systemd_capped_drain(180.0, budget) == 180.0

    def test_applies_to_in_band_restart_too_not_only_signal_stops(self):
        # The cutover was an in-band restart; gating the cap on _stop_requested_by_signal would
        # have missed the exact stop that exposed the defect.
        assert effective_stop_drain_timeout(_runner(_systemd_timeout_stop_sec=210.0)) == 210.0 - SYSTEMD_POST_DRAIN_RESERVE_S

    def test_signal_stop_takes_the_tighter_of_launchd_and_systemd(self):
        runner = _runner(
            _stop_requested_by_signal=True, _launchd_exit_timeout_s=60.0,
            _systemd_timeout_stop_sec=300.0,
        )
        assert effective_stop_drain_timeout(runner) == 50.0  # launchd 60 - 10


class TestCappedWatchdog:
    def test_leash_fires_before_systemd_kills(self):
        runner = _runner(_systemd_timeout_stop_sec=210.0)
        assert effective_stop_watchdog_delay(runner, 400.0) == 210.0 - SYSTEMD_WATCHDOG_DUMP_MARGIN_S

    def test_generous_unit_keeps_the_leash(self):
        runner = _runner(_systemd_timeout_stop_sec=600.0)
        leash = resolve_shutdown_watchdog_delay(effective_stop_drain_timeout(runner))
        assert effective_stop_watchdog_delay(runner, leash) == leash

    def test_launchd_margin_still_wins_under_launchd(self, monkeypatch):
        # Declare the host as non-systemd: this test is about launchd's budget, and the gateway
        # runs with no systemd TimeoutStopSec to cap against.
        import gateway.restart as rs

        monkeypatch.setattr(rs, "systemd_managed", lambda *a, **k: False)
        runner = _runner(_stop_requested_by_signal=True, _launchd_exit_timeout_s=60.0)
        assert effective_stop_watchdog_delay(runner, 110.0) == 60.0 - LAUNCHD_WATCHDOG_DUMP_MARGIN_S


class TestGeneratedUnitIsSelfConsistent:
    @pytest.mark.parametrize("drain,cron", [(0, 0), (60, 30), (180, 30), (180, 120), (300, 0)])
    def test_unit_never_triggers_its_own_cap(self, drain, cron):
        unit = resolve_systemd_timeout_stop_sec(drain, cron)
        assert unit - max(drain, cron) >= SYSTEMD_POST_DRAIN_RESERVE_S
        assert resolve_systemd_capped_drain(drain, unit) == drain

    def test_headroom_covers_settle_plus_tail_reserve(self):
        # settle_gateway_runtime budget (45 s) + its tail reserve (10 s) must fit in the headroom
        # the unit generator adds; 30 s provably did not.
        from gateway.run_runtime import STOP_TAIL_RESERVE_SECONDS, TURN_SETTLE_SECONDS

        assert resolve_systemd_timeout_stop_sec(180.0, 0.0) - 180.0 >= TURN_SETTLE_SECONDS + STOP_TAIL_RESERVE_SECONDS


class TestBootProbeWiring:
    def test_probe_result_is_remembered_for_the_stop_path(self, monkeypatch):
        import gateway.run_startup as rs
        import gateway.shutdown_forensics as sf

        monkeypatch.setattr(
            sf, "check_systemd_timing_alignment",
            lambda *a, **k: {
                "unit": "hermes-gateway.service", "timeout_stop_sec": 300.0,
                "drain_timeout": 180.0, "cron_drain_timeout": 30.0,
                "expected_min": 240.0, "mismatch": False,
            },
        )
        runner = SimpleNamespace(_restart_drain_timeout=180.0, _cron_drain_timeout=30.0)
        rs.GatewayStartupMixin._start_log_systemd_timing_alignment(runner)
        assert runner._systemd_timeout_stop_sec == 300.0

    def test_probe_failure_leaves_the_budget_unknown(self, monkeypatch):
        import gateway.run_startup as rs
        import gateway.shutdown_forensics as sf

        def _boom(*a, **k):
            raise RuntimeError("systemctl unavailable")

        monkeypatch.setattr(sf, "check_systemd_timing_alignment", _boom)
        runner = SimpleNamespace(_restart_drain_timeout=180.0, _cron_drain_timeout=30.0)
        rs.GatewayStartupMixin._start_log_systemd_timing_alignment(runner)  # never raises
        assert getattr(runner, "_systemd_timeout_stop_sec", None) is None
